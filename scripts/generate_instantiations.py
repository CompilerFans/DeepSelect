"""
Generate one explicit-instantiation .cu per device kernel this tree carries.

Usage, from the repo root:
    python3 scripts/generate_instantiations.py                  # every family
    python3 scripts/generate_instantiations.py xcore1600        # one family
    python3 scripts/generate_instantiations.py <instantiation_dir>
    python3 scripts/generate_instantiations.py --check          # verify only

Creates one .cu per kernel, then prints the paths (repo-root relative) to copy
into `setup.py`'s `sources`.

`--check` writes nothing: it rebuilds each family's expected file set in memory
and compares it with what is on disk -- content, not just names -- and exits
non-zero on any drift.  The three directories are the generator's output and
nothing else maintains them, so a hand edit, a half-regenerated tree, or one
family regenerated after a table change is caught here rather than by a build
that quietly compiles one family's older tuples.

The one kernel tree it generates is **`csrc/maca_kernels/xcore<N>/instantiations/`**
-- what family <N>'s artifact compiles, and the default argument (all three
families).  There the unit is a *launcher*: a host function whose body owns the
`<<<>>>` launch of exactly one device kernel, so a tuple's file carries that
kernel's device code and the launch that reaches it in one translation unit.
The headers it instantiates are the shared implementation in
`csrc/maca_kernels/common/`.  `setup.py` takes the list from
`family_sources()` rather than from the printed output, so the two cannot
drift.  All three families share the five tables today; a family-specific
tuple set is a branch on `family` in `family_instantiations()`, and it lands
with the measurement that earns it.
"""

import dataclasses
import os
import shutil
import sys
from typing import List

# Where the repo root is, from this file rather than from the caller's cwd: this
# tree is vendored inside another one, so "run it from somewhere else" is a real
# place to be standing.
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The families this build knows, and where each family's instantiation set
# lives: `csrc/maca_kernels/xcore<N>/` is family <N>'s own source directory and
# today carries exactly this directory -- the hand-written implementation the
# instantiations reference is shared, in `csrc/maca_kernels/common/`.
FAMILIES = (1000, 1500, 1600)


def instantiation_dir(family: int) -> str:
    return os.path.join(
        REPO_ROOT, "csrc", "maca_kernels", f"xcore{family}", "instantiations")


# ═══════════════════════════════════════════════════════════════════════════
# csrc/maca_kernels/xcore<N>/instantiations/ -- one directory per family
# ═══════════════════════════════════════════════════════════════════════════
#
# The unit here is a *launcher*: the host function whose body owns the
# `<<<>>>` launch of one device kernel.  Instantiating it in its own file puts
# the kernel's device code and the only launch that reaches it in the same
# translation unit, which is what makes the artifact carry the kernel exactly
# once -- the dispatch side declares the launcher `extern template` instead of
# defining it, so a tuple missing from these tables is an undefined symbol at
# link rather than a duplicate.
#
# Five tables, one per group of kernels the artifact carries.  The file count
# per group is the receipt: `ls instantiations/*.cu | wc -l` equals the number
# of `__device_stub__` symbols the artifact defines.


@dataclasses.dataclass(frozen=True)
class Instantiation:
    """One device kernel: the file that carries it, and its one instantiation."""

    group: str
    name: str            # the file stem -- the tuple, spelled out
    namespace: str       # where the launcher template is declared
    header: str          # relative to the instantiations/ directory
    instantiation: str   # the `template ...<args>(params);` it writes

    @property
    def file_name(self) -> str:
        return self.name + ".cu"

    def file_text(self) -> str:
        return (
            "// Generated by scripts/generate_instantiations.py -- do not edit.\n"
            f"// {self.group}: {self.name}\n"
            "\n"
            f'#include {self.header}\n'
            "\n"
            f"namespace {self.namespace} {{\n"
            "\n"
            f"{self.instantiation}\n"
            "\n"
            f"}}  // namespace {self.namespace}\n"
        )


def _inst(group, name, namespace, header, instantiation) -> Instantiation:
    return Instantiation(group, name, namespace, header, instantiation)


# The headers are the shared implementation in `common/`; an instantiation
# directory sits two levels below it.
CONTRACT_HEADER = "<csrc/maca_kernels/common/contract.cuh>"
SPLIT_HEADER = "<csrc/maca_kernels/common/radix_chunked.cuh>"
COARSE12_HEADER = "<csrc/maca_kernels/common/topk_coarse12.cuh>"
CHUNKS_HEADER = "<csrc/maca_kernels/common/topk_chunks.cuh>"

# ── row: `topk_kernel_radix<Cfg>` ───────────────────────────────────────────
#
# The axes are `docs/code-architecture.zh.md` §5b's, in the config's own
# spelling `TopkRadixConfig<ValueT, OutIdxT, BLOCK, SI, RV, SV, PRE>`, which is
# also the spelling the table in `maca_topk.cu` uses.  The two lists must agree;
# a tuple here that the table does not carry is an unused instantiation, and one
# the table wants that this list does not carry is an undefined symbol.
#
# The 60 tuples are two arms of that one kernel: `PRE=false` (30) is the row
# dataflow selecting for itself, and `PRE=true` (30) is the contract half
# emitting a row whose candidates a staged route already chose.
ROW_VALUE_TYPES = (("bf16", "maca_bfloat16"), ("fp32", "float"))
ROW_INDEX_TYPES = (("i32", "int32_t"), ("i64", "int64_t"))
# (SI, SV, RV).  `sorted_value` implies `return_value` and is exclusive with
# `sorted_index`, so five of the eight combinations are reachable and they are
# these five.
ROW_FLAGS = ((0, 0, 0), (0, 0, 1), (1, 0, 0), (1, 0, 1), (1, 1, 1))
# The wide block is the 16-bit row's; the fp32 row has one width.
ROW_BLOCKS = {"bf16": (512, 1024), "fp32": (512,)}
ROW_SIGNATURE = ("const deep_select::RowParams &params, uint32_t batches, "
                 "cudaStream_t stream, size_t smem")


def _b(flag: int) -> str:
    return "true" if flag else "false"


def row_instantiations() -> List[Instantiation]:
    out = []
    for value_tag, value_type in ROW_VALUE_TYPES:
        for idx_tag, idx_type in ROW_INDEX_TYPES:
            for block in ROW_BLOCKS[value_tag]:
                for si, sv, rv in ROW_FLAGS:
                    for pre in (0, 1):
                        cfg = (f"deep_select::TopkRadixConfig<{value_type}, "
                               f"{idx_type}, {block}, {_b(si)}, {_b(rv)}, "
                               f"{_b(sv)}, {_b(pre)}>")
                        out.append(_inst(
                            "row",
                            f"value_{value_tag}_outidx_{idx_tag}_block_{block}"
                            f"_si{si}_rv{rv}_sv{sv}_pre{pre}",
                            "deep_select::detail", CONTRACT_HEADER,
                            f"template void launch_radix_config<{cfg}>(\n"
                            f"    {ROW_SIGNATURE});"))
    return out


# ── split: the two-stage split's stage kernels ──────────────────────────────
#
# Four arms, twelve kernels: the 16-bit split's static-k arm (stage 1 x
# `kNan`, stage 2 per `TOPK`), the same split's runtime-`topk` arm (stage 1 x
# `kNan`, stage 2 once), and the fp32 split (stage 1 x `kNan`, stage 2 once).
# The composing entry points (`launch_topk_bf16_chunked_k`, and `routing.cuh`'s
# `launch_typed_chunked` / `launch_typed_f32_chunked`, which pick the arm)
# call these; they own no launch of their own.
CHUNK_BLOCK = "kChunkBlockSize"
F32_CHUNK_BLOCK = "kBlockSize"


def split_instantiations() -> List[Instantiation]:
    out = []
    for topk in (512, 1024):
        for nan in (0, 1):
            out.append(_inst(
                "split", f"bf16_stage1_k_topk{topk}_nan{nan}",
                "topk_select_radix", SPLIT_HEADER,
                f"template cudaError_t launch_bf16_chunk_stage1_k<{topk}u, "
                f"{_b(nan)}>(\n"
                "    const maca_bfloat16 *scores, const int32_t *lengths,\n"
                "    int32_t *candidate_indices, maca_bfloat16 *candidate_values,\n"
                "    int B, int L, int num_chunks, cudaStream_t stream,\n"
                "    int64_t score_stride, int32_t *nan_flags);"))
        out.append(_inst(
            "split", f"bf16_stage2_k_topk{topk}",
            "topk_select_radix", SPLIT_HEADER,
            f"template cudaError_t launch_bf16_chunk_stage2_k<{topk}u>(\n"
            "    const maca_bfloat16 *candidate_values,\n"
            "    const int32_t *candidate_indices, int32_t *indices, int B,\n"
            "    int num_chunks, cudaStream_t stream);"))
    for nan in (0, 1):
        out.append(_inst(
            "split", f"bf16_stage1_topk_runtime_nan{nan}",
            "topk_select_radix", SPLIT_HEADER,
            f"template cudaError_t launch_bf16_chunk_stage1_runtime<{_b(nan)}>(\n"
            "    const maca_bfloat16 *scores, const int32_t *lengths,\n"
            "    int32_t *candidate_indices, maca_bfloat16 *candidate_values,\n"
            "    int B, int L, int topk, int num_chunks, cudaStream_t stream,\n"
            "    int64_t score_stride, int32_t *nan_flags);"))
    out.append(_inst(
        "split", "bf16_stage2_topk_runtime",
        "topk_select_radix", SPLIT_HEADER,
        f"template cudaError_t launch_bf16_chunk_stage2_runtime<{CHUNK_BLOCK}>(\n"
        "    const maca_bfloat16 *candidate_values,\n"
        "    const int32_t *candidate_indices, int32_t *indices, int B,\n"
        "    int num_chunks, int topk, cudaStream_t stream);"))
    for nan in (0, 1):
        out.append(_inst(
            "split", f"fp32_stage1_nan{nan}",
            "topk_select_radix", SPLIT_HEADER,
            f"template cudaError_t launch_f32_chunk_stage1<{_b(nan)}>(\n"
            "    const float *scores, const int32_t *lengths, int32_t *cols,\n"
            "    float *vals, int B, int L, int topk, int num_chunks,\n"
            "    cudaStream_t stream, int64_t score_stride, int32_t *nan_flags);"))
    out.append(_inst(
        "split", "fp32_stage2", "topk_select_radix", SPLIT_HEADER,
        f"template cudaError_t launch_f32_chunk_stage2<{F32_CHUNK_BLOCK}>(\n"
        "    const float *vals, const int32_t *cols, int32_t *out, int B,\n"
        "    int topk, int num_chunks, cudaStream_t stream);"))
    return out


# ── coarse12: the ported `topk_coarse12` selector ───────────────────────────


def coarse12_instantiations() -> List[Instantiation]:
    return [_inst(
        "coarse12", "coarse12_kernel", "topk_select_coarse12", COARSE12_HEADER,
        "template cudaError_t launch_coarse12_kernel<kThreads>(\n"
        "    const float *scores, const int32_t *lengths, int32_t *out,\n"
        "    int32_t *nan_flags, int B, int topk, int64_t stride,\n"
        "    int default_length, uint16_t *block_max, uint32_t *block_list,\n"
        "    cudaStream_t stream);")]


# ── chunks: the ported `topk_chunks` selector ───────────────────────────────
#
# Three kernels per `ChunkCount`, and `ChunkCount` is what
# `select_chunk_count` resolves the shape to.

CHUNK_COUNTS = (3, 4, 5, 6)


def chunks_instantiations() -> List[Instantiation]:
    out = []
    for count in CHUNK_COUNTS:
        out.append(_inst(
            "chunks", f"chunks_init_c{count}", "topk_select_chunks", CHUNKS_HEADER,
            f"template cudaError_t launch_chunks_init<{count}>(\n"
            "    void *workspace, const int32_t *lengths, int rows,\n"
            "    int default_length, cudaStream_t stream);"))
        out.append(_inst(
            "chunks", f"chunks_coarse_hist_c{count}", "topk_select_chunks",
            CHUNKS_HEADER,
            f"template cudaError_t launch_chunks_coarse_hist<{count}>(\n"
            "    const float *scores, void *workspace, int32_t *nan_flags,\n"
            "    int topk, int64_t stride, int default_length, int rows,\n"
            "    cudaStream_t stream);"))
        out.append(_inst(
            "chunks", f"chunks_compact_refine_c{count}", "topk_select_chunks",
            CHUNKS_HEADER,
            f"template cudaError_t launch_chunks_compact_refine<{count}>(\n"
            "    const float *scores, int32_t *out, void *workspace, int topk,\n"
            "    int64_t stride, int default_length, int rows, cudaStream_t stream);"))
    return out


# ── nan: the NaN contract's device half ─────────────────────────────────────
#
# It is not shape-selected: its two kernels are launched from the ladder and the
# entry point rather than chosen by a predicate.  They are in the table because
# the artifact carries them -- a `__global__` is emitted whether or not anything
# launches it -- and the file count is what says so.


def nan_instantiations() -> List[Instantiation]:
    return [
        _inst("nan", "nan_scan_fp32", "deep_select", CONTRACT_HEADER,
              "template void launch_nan_scan<float>(\n"
              "    const void *input, const int32_t *lengths, int64_t stride_elems,\n"
              "    uint32_t vocab_size, uint32_t chunks, int32_t *flags,\n"
              "    uint32_t batches, cudaStream_t stream);"),
        _inst("nan", "nan_abort", "deep_select", CONTRACT_HEADER,
              "template void launch_nan_abort<kNanAbortBlock>(\n"
              "    const int32_t *flags, uint32_t batches, cudaStream_t stream);"),
    ]


def family_instantiations(family: int) -> List[Instantiation]:
    """Every device kernel family `family`'s artifact carries, one per kernel.

    All three families share the five tables today.  A family-specific tuple
    set is a branch on `family` here, and it lands with the measurement that
    earns it -- a tuple only one family's artifact carries is that family's
    kernel, which is what the per-family directory is for.
    """
    if family not in FAMILIES:
        raise ValueError(f"unknown family {family!r}; known: {FAMILIES}")
    return (row_instantiations() + split_instantiations()
            + coarse12_instantiations() + chunks_instantiations()
            + nan_instantiations())


def family_sources(family: int) -> List[str]:
    """The generated sources, repo-root-relative -- what `setup.py` compiles."""
    return [os.path.relpath(os.path.join(instantiation_dir(family), i.file_name),
                            REPO_ROOT)
            for i in family_instantiations(family)]


def group_counts(instantiations: List[Instantiation]) -> List[tuple]:
    """`(group, tuple count)` in table order -- the per-group receipt."""
    counts = []
    for inst in instantiations:
        if counts and counts[-1][0] == inst.group:
            counts[-1] = (inst.group, counts[-1][1] + 1)
        else:
            counts.append((inst.group, 1))
    return counts


def _checked(family: int) -> List[Instantiation]:
    """The family's table, with the one invariant a file name carries checked."""
    everything = family_instantiations(family)
    names = [i.file_name for i in everything]
    if len(set(names)) != len(names):
        raise ValueError("two tuples share a file name")
    return everything


def file_texts(family: int) -> dict:
    """The family's expected file set: `{file name: text}`, from the tables.

    One description of the output -- the tables plus `Instantiation.file_text()`
    -- read by both the writer and `--check`, so the checker cannot certify
    something the writer would not produce.
    """
    return {i.file_name: i.file_text() for i in _checked(family)}


def write_family(family: int) -> List[Instantiation]:
    """Remake the family's directory and write one file per tuple."""
    out_dir = instantiation_dir(family)
    everything = _checked(family)
    if os.path.exists(out_dir):
        shutil.rmtree(out_dir)
    os.makedirs(out_dir)
    for inst in everything:
        with open(os.path.join(out_dir, inst.file_name),
                  "w", encoding="utf-8") as f:
            f.write(inst.file_text())
    return everything


def check_family(family: int) -> List[str]:
    """The family's drift against the tables, one line per file.  Empty is clean.

    Compares content, not only names: `setup.py` rejects a table file that is
    missing, so the name-side check is already made at build; what it cannot see
    is a file whose body no longer matches its table row, a table file no longer
    produced, or a directory one table edit behind.
    """
    expected = file_texts(family)
    out_dir = instantiation_dir(family)
    if not os.path.isdir(out_dir):
        return [f"the directory is missing: {out_dir}"]
    on_disk = sorted(n for n in os.listdir(out_dir) if n.endswith(".cu"))
    problems = []
    for name in sorted(set(expected) - set(on_disk)):
        problems.append(f"missing  {name}")
    for name in sorted(set(on_disk) - set(expected)):
        problems.append(f"extra    {name}")
    for name in sorted(set(expected) & set(on_disk)):
        with open(os.path.join(out_dir, name), encoding="utf-8") as f:
            if f.read() != expected[name]:
                problems.append(f"differs  {name}")
    return problems


def resolve_family(target: str) -> int:
    """A family spelled `xcore<N>`, or a family's instantiation directory."""
    if target.startswith("xcore") and target[len("xcore"):].isdigit():
        family = int(target[len("xcore"):])
    else:
        norm = os.path.normpath(target)
        family = next(
            (f for f in FAMILIES
             if norm == os.path.relpath(instantiation_dir(f), REPO_ROOT)),
            None)
    if family not in FAMILIES:
        raise ValueError(f"Invalid `target: {target}")
    return family


def main(target: str, check: bool = False) -> int:
    family = resolve_family(target)
    if check:
        problems = check_family(family)
        print(f"xcore{family}: {len(file_texts(family))} expected, "
              f"{'clean' if not problems else str(len(problems)) + ' differ'}",
              file=sys.stderr)
        for line in problems:
            print(f"  {line}", file=sys.stderr)
        return 0 if not problems else 1
    written = write_family(family)
    for group, count in group_counts(written):
        print(f"# {group}: {count}", file=sys.stderr)
    print(f"# total: {len(written)}", file=sys.stderr)
    for path in family_sources(family):
        print(f"\"{path}\",")
    return 0


if __name__ == '__main__':
    argv = sys.argv[1:]
    check = "--check" in argv
    argv = [a for a in argv if a != "--check"]
    if len(argv) > 1:
        print(f"Usage: {sys.argv[0]} [--check] [xcore<N>|<instantiation_dir>]",
              file=sys.stderr)
        sys.exit(1)
    # No target is every family this build compiles.
    status = 0
    for target in (argv or [f"xcore{f}" for f in FAMILIES]):
        status |= main(target, check)
    if check:
        print("# check: clean" if status == 0 else "# check: DRIFT",
              file=sys.stderr)
    sys.exit(status)
